RULE_FILE = 'flypy_vocabulary_rules.tsv'
LUA_FILE = 'lua/flypy_vocabulary_filter.lua'
FILTER = 'lua_filter@*flypy_vocabulary_filter'
LUA = '''-- Personal vocabulary overrides; generated by Flypy Settings.
local M = {}
function M.init(env)
  env.rules = {}
  env.has_pin = false
  local f = require("flypy_learning").open(env,"flypy_vocabulary_rules.tsv","r")
  if not f then return end
  for line in f:lines() do
    if line:sub(1,1) ~= "#" then
      local old, text, mode, alias, tw = line:match("^([^\\t]+)\\t([^\\t]*)\\t([^\\t]+)\\t([^\\t]*)\\t(.*)$")
      if old then
        local rule = {text=text, mode=mode, tw=tw}
        env.rules[old] = rule
        if mode == "pin" then env.has_pin = true end
        -- Legacy simplified-only keys may use their displayed alias; shared forms stay distinct.
        if alias ~= "" and require('flypy_number_style').exact(old) ~= old then env.rules[alias] = rule end
      end
    end
  end
  f:close()
end
function M.func(input, env)
  if next(env.rules) == nil then
    for cand in input:iter() do yield(cand) end
    return
  end
  local buffered, pinned, n = {}, {}, 0
  local function transform(cand)
    local rule = env.rules[cand.text]
    if rule and rule.mode == "hide" then return nil end
    if rule and rule.text ~= "" then
      local text = env.engine.context:get_option("traditionalization") and rule.tw or rule.text
      if text ~= cand.text then cand = ShadowCandidate(cand, cand.type, text, cand.comment) end
    end
    return cand, rule and rule.mode == "pin" and cand._end == #env.engine.context.input
  end
  if not env.has_pin then
    for cand in input:iter() do
      local c = transform(cand)
      if c then yield(c) end
    end
    return
  end
  -- Bound look-ahead to keep long/infinite translations responsive.
  for cand in input:iter() do
    local c, pin = transform(cand)
    n = n + 1
    if n <= 256 then
      if c then table.insert(pin and pinned or buffered, c) end
    else
      if n == 257 then
        for _, x in ipairs(pinned) do yield(x) end
        for _, x in ipairs(buffered) do yield(x) end
      end
      if c then yield(c) end
    end
  end
  if n <= 256 then
    for _, x in ipairs(pinned) do yield(x) end
    for _, x in ipairs(buffered) do yield(x) end
  end
end
return M
'''

def display(store, text):
    return store.to_tw.convert(text)

@dataclass(eq=True)
class Rule:
    original: str
    replacement: str = ''
    mode: str = 'normal'
    traditional: str | None = None

class Rules:
    def __init__(self, store):
        self.store = store
        self.rows = {}
        raw = store.raw.get(RULE_FILE)
        if raw:
            for line in raw.decode('utf-8-sig').splitlines():
                if not line or line.startswith('#'):
                    continue
                fields = line.split('\t')
                if len(fields) != 5 or fields[2] not in ('normal', 'pin', 'hide'):
                    raise SettingsError('個人詞彙規則格式不正確，未修改檔案。')
                self.rows[fields[0]] = Rule(*fields[:3], traditional=fields[4] if fields[1] else None)
        self.original = dict(self.rows)

    def put(self, rule):
        if not rule.original or rule.mode not in ('normal', 'pin', 'hide') or any(c in rule.original + rule.replacement + (rule.traditional or '') for c in '\t\r\n\0'):
            raise SettingsError('詞彙規則不能含 Tab、換行或空字詞。')
        exact = rule.traditional if rule.traditional is not None else rule.replacement
        internal = self.store.to_s.convert(rule.original) if rule.replacement and display(self.store, rule.original) == exact else self.store.to_s.convert(rule.replacement)
        rule = Rule(rule.original, internal, rule.mode,
                    (rule.traditional if rule.traditional is not None else rule.replacement) if rule.replacement else None)
        if not rule.replacement and rule.mode == 'normal':
            self.rows.pop(rule.original, None)
        else:
            self.rows[rule.original] = rule

    def output(self, rule):
        return rule.traditional if rule.traditional is not None else display(self.store, rule.replacement)

    def display(self, text):
        rule = self.rows.get(text)
        return self.output(rule) if rule and rule.replacement else display(self.store, text)

    def build(self, base, catalogue):
        result = dict(base)
        if self.rows == self.original:
            return result
        lines = ['# 原文\t替代文字（內部）\t規則\t台灣顯示原文\t台灣替代文字\n']
        for key in sorted(self.rows):
            rule = self.rows[key]
            lines.append('\t'.join([key, rule.replacement, rule.mode, display(self.store, key), self.output(rule)]) + '\n')
        result[RULE_FILE] = ''.join(lines).encode('utf-8')
        result[LUA_FILE] = LUA.encode('utf-8')
        name = 'double_pinyin_flypy.custom.yaml'
        data = result.get(name, self.store.raw[name])
        doc = yaml_parser().load(data.decode('utf-8-sig')) if data else {'patch': {}}
        from settings_core import get_patch
        filters = get_patch(doc, 'engine/filters')
        if filters is None:
            filters = catalogue.effective['double_pinyin_flypy']['engine']['filters']
        filters = list(filters)
        if FILTER not in filters:
            pos = filters.index('uniquifier') if 'uniquifier' in filters else len(filters)
            filters.insert(pos, FILTER)
        set_patch(doc, 'engine/filters', filters)
        result[name] = dump_yaml(doc).encode('utf-8')
        return {k: v for k, v in result.items() if v != self.store.raw[k]}

def dictionary_header(path):
    lines = []
    with path.open(encoding='utf-8-sig') as stream:
        for line in stream:
            if line.strip() == '...':
                break
            lines.append(line)
    return yaml_parser().load(''.join(lines)) or {}

class Index:
    def __init__(self, root):
        self.root = Path(root)
        cache_root = Path(os.environ.get('LOCALAPPDATA', str(self.root / 'maintenance'))) / 'FlypySettings' / 'cache'
        identity = hashlib.sha256(str(self.root.resolve()).casefold().encode('utf-8')).hexdigest()[:20]
        self.folder = cache_root / identity
        self.path = self.folder / 'vocabulary-v2.sqlite3'
        self.to_source = OpenCC('t2s')  # Search preserves vocabulary, as output does.
        self.to_s = OpenCC('t2s')
        self.to_tw = TaiwanConverter()
        self.lock = threading.RLock()

    def sources(self):
        active = set()
        def imports(name):
            relative = name + '.dict.yaml'
            if relative in active:
                return
            active.add(relative)
            path = self.root / relative
            if path.is_file():
                for child in dictionary_header(path).get('import_tables', []):
                    imports(child)
        # Use resolved translator configuration, not a hard-coded dictionary choice.
        schema = self.root / 'build' / 'double_pinyin_flypy.schema.yaml'
        config = yaml_parser().load(schema.read_text(encoding='utf-8-sig')) if schema.is_file() else {}
        for key in ('translator', 'melt_eng', 'radical_lookup'):
            name = config.get(key, {}).get('dictionary')
            if name:
                imports(name)
        for key in ('custom_phrase', 'cn_en'):
            name = config.get(key, {}).get('user_dict')
            if name:
                active.add(name + '.txt')
        paths = list(self.root.glob('*.dict.yaml'))
        if (self.root / 'flypy_learning.tsv').is_file():
            paths.append(self.root / 'flypy_learning.tsv')
        for folder in ('cn_dicts', 'en_dicts'):
            paths.extend((self.root / folder).glob('*.dict.yaml'))
            paths.extend((self.root / folder).glob('*.txt'))
        if (self.root / 'flypy_phrases.txt').is_file():
            paths.append(self.root / 'flypy_phrases.txt')
        learned = self.root / 'maintenance' / 'learned-export'
        if learned.is_dir():
            paths.extend(learned.glob('*.txt'))
        else:
            installation = self.root / 'installation.yaml'
            if installation.is_file():
                identity = yaml_parser().load(installation.read_text(encoding='utf-8-sig')).get('installation_id', '')
                if identity and Path(identity).name == identity:
                    paths.extend((self.root / 'sync' / identity).glob('*.userdb.txt'))
        result = []
        for path in sorted(set(paths)):
            rel = path.relative_to(self.root).as_posix()
            kind = '台灣詞庫' if rel == 'flypy_taiwan.dict.yaml' else '自動學習' if rel == 'flypy_learning.tsv' or 'learned-export/' in rel or rel.endswith('.userdb.txt') else '個人詞彙' if rel.startswith('flypy_') else '英文' if '/en' in rel or rel.startswith('melt_eng') else '中英混輸' if 'cn_en' in rel else '拆字反查' if rel.startswith('radical') else '中文'
            enabled = rel in active or kind == '自動學習' or rel == 'flypy_personal.dict.yaml'
            result.append((path, rel, kind, enabled))
        return result

    def rows(self, path, source, kind, active):
        if source == 'flypy_learning.tsv':
            from quick_learning import records
            for line_no, (text, code, weight) in enumerate(records(self.root), 1):
                yield (source, line_no, kind, int(active), text, code, weight)
            return
        is_dict = path.name.endswith('.dict.yaml')
        header = dictionary_header(path) if is_dict else {}
        columns = header.get('columns', ['text', 'code', 'weight'])
        started = not is_dict
        with path.open(encoding='utf-8-sig') as stream:
            for line_no, line in enumerate(stream, 1):
                if not started:
                    started = line.strip() == '...'
                    continue
                line = line.rstrip('\r\n')
                if not line or line.startswith('#'):
                    continue
                fields = line.split('\t')
                if kind == '自動學習':
                    if len(fields) < 3:
                        continue
                    if source.endswith('.userdb.txt'):
                        code, text, weight = fields[0].strip(), fields[1], fields[2]
                    else:
                        text, code, weight = fields[:3]
                else:
                    row = dict(zip(columns, fields))
                    text = row.get('text', '')
                    code = row.get('code', '')
                    weight = row.get('weight', '')
                if text:
                    yield (source, line_no, kind, int(active), text, code, weight)

    def rebuild(self, force=False):
        with self.lock:
            return self._rebuild(force)

    def _rebuild(self, force=False):
        self.folder.mkdir(parents=True, exist_ok=True)
        sources = self.sources()
        fingerprint = json.dumps([(rel, p.stat().st_size, p.stat().st_mtime_ns, a) for p, rel, k, a in sources])
        marker = self.folder / 'sources-v2.json'
        if not force and self.path.exists() and marker.exists() and marker.read_text(encoding='utf-8') == fingerprint:
            return
        temp = self.folder / 'building.sqlite3'
        # Only an owned, disposable index is recreated; no Rime dictionary is changed.
        if temp.exists():
            temp.unlink()
        try:
            with closing(sqlite3.connect(temp)) as db:
                db.execute('PRAGMA journal_mode=OFF')
                db.execute('CREATE TABLE words(id INTEGER PRIMARY KEY, source TEXT, line INTEGER, kind TEXT, active INTEGER, text TEXT, code TEXT, weight TEXT)')
                for path, source, kind, active in sources:
                    db.executemany('INSERT INTO words(source,line,kind,active,text,code,weight) VALUES(?,?,?,?,?,?,?)', self.rows(path, source, kind, active))
                db.execute('CREATE INDEX source_index ON words(source,id)')
                db.execute('CREATE INDEX kind_index ON words(kind,active,id)')
                db.execute('CREATE INDEX word_index ON words(text)')
                db.commit()
            os.replace(temp, self.path)
            marker.write_text(fingerprint, encoding='utf-8')
        finally:
            temp.unlink(missing_ok=True)

    def query(self, text='', kind='全部', enabled='全部', source='全部來源', page=0, size=100, exclude_personal=False, offset=None, include_count=True, extra_terms=()):
        where, values = [], []
        if exclude_personal:
            where.append("source NOT IN ('flypy_personal.dict.yaml','flypy_phrases.txt','flypy_learning.tsv')")
        if text.strip():
            query = text.strip()
            terms = list(dict.fromkeys([query, self.to_source.convert(query), self.to_s.convert(query), self.to_tw.convert(query), *extra_terms]))
            parts = []
            for term in terms:
                escaped = term.replace('\\', '\\\\').replace('%', '\\%').replace('_', '\\_')
                parts.append("(text LIKE ? ESCAPE '\\' OR code LIKE ? ESCAPE '\\')")
                values.extend(['%' + escaped + '%'] * 2)
            where.append('(' + ' OR '.join(parts) + ')')
        if kind != '全部':
            where.append('kind=?'); values.append(kind)
        if enabled != '全部':
            where.append('active=?'); values.append(int(enabled == '已啟用'))
        if source != '全部來源':
            where.append('source=?'); values.append(source)
        clause = ' WHERE ' + ' AND '.join(where) if where else ''
        with self.lock, closing(sqlite3.connect(self.path)) as db:
            db.row_factory = sqlite3.Row
            count = db.execute('SELECT count(*) FROM words' + clause, values).fetchone()[0] if include_count else 0
            rows = [dict(r) for r in db.execute('SELECT * FROM words' + clause + ' ORDER BY id LIMIT ? OFFSET ?', values + [size, page * size if offset is None else offset])]
            total = db.execute('SELECT count(*) FROM words').fetchone()[0] if include_count else 0
        return rows, count, total

    def source_counts(self):
        with self.lock, closing(sqlite3.connect(self.path)) as db:
            return list(db.execute('SELECT source,kind,active,count(*) FROM words GROUP BY source,kind,active ORDER BY source'))

    def exact(self, text):
        with self.lock, closing(sqlite3.connect(self.path)) as db:
            db.row_factory = sqlite3.Row
            return [dict(r) for r in db.execute('SELECT * FROM words WHERE text=?', (text,))]

    def export_csv(self, destination, store):
        import csv
        with self.lock, closing(sqlite3.connect(self.path)) as db, Path(destination).open('w', encoding='utf-8-sig', newline='') as stream:
            writer = csv.writer(stream)
            writer.writerow(['原始詞彙', '完整拼音或輸入碼', '權重或學習數據', '來源', '類型', '已啟用'])
            # Preserve raw data in bulk exports; no slow whole-dictionary conversion.
            writer.writerows(db.execute('SELECT text,code,weight,source,kind,active FROM words ORDER BY id'))

def refresh_learned(store):
    """Export through official librime levers API while its server is stopped."""
    import subprocess
    import sys
    store.assert_active_user_dir()
    if not store.weasel_root:
        raise SettingsError('找不到小狼毫程式位置。')
    root = store.weasel_root
    options = dict(creationflags=subprocess.CREATE_NO_WINDOW if os.name == 'nt' else 0,
                   stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    server = root / 'WeaselServer.exe'
    destination = store.root / 'maintenance' / 'learned-export'
    destination.mkdir(parents=True, exist_ok=True)
    command = [sys.executable] if getattr(sys, 'frozen', False) else [sys.executable, str(Path(__file__).with_name('flypy_settings.py'))]
    try:
        subprocess.run([str(server), '/quit'], timeout=15, check=True, **options)
        result = subprocess.run(command + ['--export-learned', str(store.root), str(root), str(destination)], timeout=60, **options)
        if result.returncode:
            raise SettingsError('無法匯出學習記憶；原詞頻未改動。' + result.stderr.decode('utf-8', errors='replace')[-600:])
    finally:
        subprocess.Popen([str(server)], creationflags=options['creationflags'], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    return destination
